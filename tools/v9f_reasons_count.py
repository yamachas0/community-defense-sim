def classify(text, mapping):
    if text in mapping:
        return mapping[text]
    if text:
        print(f"[warning] 未分類の原文（辞書に無い）: {text!r}", file=sys.stderr)
        return "MISSING"
    return None


def has_any(text, words):
    return any(w in text for w in words)


def shape_of(parcel, start_ledger):
    x = start_ledger.get(parcel)
    if not x:
        return "不明"
    if x.get("tenant"):
        return "借家がある区画"
    if x.get("building") and x["building"] != x["land"]:
        return "借地の区画"
    return "所有者が使っている区画"


def tally_by(items, key_fn, cat_fn):
    groups = defaultdict(Counter)
    ns = Counter()
    for it in items:
        k = key_fn(it)
        c = cat_fn(it)
        groups[k][c] += 1
        ns[k] += 1
    return groups, ns


def print_group_table(groups, ns, order=None):
    keys = order or sorted(ns.keys(), key=lambda k: -ns[k])
    for k in keys:
        n = ns[k]
        print(f"  {k}  n={n}")
        for cat in [1, 2, 3, 4]:
            c = groups[k].get(cat, 0)
            pct = f"{c / n * 100:.1f}%" if n else "-"
            print(f"    {CAT_LABEL[cat]}: {c} ({pct})")


def ratio_bin(r):
    if r < 1.0:
        return "<1.0"
    if r < 1.2:
        return "1.0-1.2"
    if r < 1.5:
        return "1.2-1.5"
    return ">=1.5"


